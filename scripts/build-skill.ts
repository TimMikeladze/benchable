/**
 * Builds `skills/benchable/scripts/benchable.mjs`: the CLI as one Node 18+ file with no
 * dependencies. The skill runs
 * this file, so it is committed; CI rebuilds it and fails on a diff. See docs/agent-skill.md.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";

const root = join(import.meta.dir, "..");
const out = join(root, "skills/benchable/scripts/benchable.mjs");

const result = await Bun.build({
  entrypoints: [join(root, "src/cli/benchable.ts")],
  target: "node",
  format: "esm",
  minify: true,
  define: {
    "process.env.NODE_ENV": '"production"',
  },
});
if (!result.success) {
  console.error(result.logs.map(String).join("\n"));
  process.exit(1);
}

// Bun keeps the source's `#!/usr/bin/env bun`; the shipped file runs under Node.
const code = (await result.outputs[0]!.text()).replace(/^#!.*\n/, "");
mkdirSync(dirname(out), { recursive: true });
writeFileSync(
  out,
  `#!/usr/bin/env node\n// Generated by \`bun run skill:build\` from src/cli/benchable.ts. Do not edit.\n${code}`,
);
console.log(`wrote ${out.slice(root.length + 1)} (${Math.round(code.length / 1024)} KB)`);
